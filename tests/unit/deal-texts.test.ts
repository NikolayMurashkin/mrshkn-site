/** Формула гарантии по языкам: гарантия покрывает и поломку по нашей вине, и расхождение с договором. */
const WARRANTY_FORMULA: Record<'ru' | 'en', { long: string; short: string }> = {
  ru: {
    long: 'все, что сломалось по\u00a0нашей вине или работает не\u00a0так, как записано в\u00a0договоре',
    short:
      'Сломалось по\u00a0нашей вине или работает не\u00a0так, как записано в\u00a0договоре,\u00a0— чиним бесплатно',
  },
  en: {
    long: 'anything that broke through our fault or does not work the way the contract says',
    short: 'Broke through our fault or not as the contract says: free fix',
  },
};

/** Все строковые значения JSON рекурсивно, с путем. */
const entriesOf = (value: unknown, path = ''): Entry[] => {
  if (typeof value === 'string') {
    return [{ path, text: value }];
  }

  if (value !== null && typeof value === 'object') {
    return Object.entries(value).flatMap(([key, child]) => entriesOf(child, path === '' ? key : `${path}.${key}`));
  }

  return [];
};

const valueAt = (root: unknown, path: string): unknown =>
  path.split('.').reduce<unknown>((node, key) => {
    if (node !== null && typeof node === 'object') {
      return (node as Record<string, unknown>)[key];
    }

    return undefined;
  }, root);

const sourceFiles = (dir: string): string[] =>
  readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);

    if (statSync(path).isDirectory()) {
      return sourceFiles(path);
    }

    return /\.tsx?$/.test(name) ? [path] : [];
  });

const SEARCHED: Entry[] = [
  ...entriesOf(ru).map(({ path, text }) => ({ path: `messages/ru.json ${path}`, text })),
  ...entriesOf(en).map(({ path, text }) => ({ path: `messages/en.json ${path}`, text })),
  ...sourceFiles('src').map((path) => ({ path, text: readFileSync(path, 'utf8') })),
];

/** Видимый текст разметки: без тегов и с раскрытыми сущностями HTML. */
const visibleText = (html: string) =>
  html
    .replace(/<[^>]*>/g, '')
    .replaceAll('&quot;', '"')
    .replaceAll('&#x27;', "'")
    .replaceAll('&lt;', '<')
    .replaceAll('&gt;', '>')
    .replaceAll('&amp;', '&');

const pricingText = (locale: string, messages: typeof ru, Section: (props: SectionProps) => ReactNode) =>
  visibleText(
    renderToStaticMarkup(
      createElement(
        Provider,
        { locale, timeZone: 'Europe/Moscow', messages },
        Section({ section: 'pricing' } as unknown as SectionProps),
      ),
    ),
  );

const homeMetadata = async (locale: string): Promise<Metadata> => {
  const { generateMetadata } = (await import('@/app/[locale]/layout')) as { generateMetadata: GenerateMetadata };

  return generateMetadata({ params: Promise.resolve({ locale }) as Promise<never> });
};

/** Заголовок строкой или объектом `{ default, absolute }` — как его отдает layout. */
const titleText = (title: Metadata['title']): string => {
  if (typeof title === 'string') {
    return title;
  }

  if (title && typeof title === 'object') {
    const { absolute, default: fallback } = title as { absolute?: string; default?: string };

    return absolute ?? fallback ?? '';
  }

  return '';
};

