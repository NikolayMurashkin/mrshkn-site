/** Прежняя дата редакции политики: форма замера меняет политику → строка обязана смениться. */
const PREVIOUS_PRIVACY_UPDATED = 'Редакция от 23 октября 2026';

/** Разделы английской политики, где описана форма: какие данные и зачем, кому передаем. */
const EN_FORM_SECTIONS = ['data', 'transfer'] as const;

/** Название формы в английской политике — то же, что заголовок секции в `en.json`. */
const EN_FORM_TITLE = 'Check your site';

/** Значение по пути вида `privacy.sections.data.paragraphs[0]`: точки — ключи, `[n]` — индекс массива. */
const valueAt = (messages: unknown, path: string): unknown =>
  path
    .split(/\.|\[(\d+)\]/)
    .filter(Boolean)
    .reduce<unknown>(
      (node, key) => (node !== null && typeof node === 'object' ? (node as Record<string, unknown>)[key] : undefined),
      messages,
    );

/** Все строки значения: объекты и массивы обходятся целиком. */
const stringsOf = (value: unknown): string[] => {
  if (typeof value === 'string') {
    return [value];
  }

  return value !== null && typeof value === 'object' ? Object.values(value).flatMap(stringsOf) : [];
};

const AUDIT_PATHS = APPROVED.map(([path]) => path).filter((path) => path.startsWith('audit.'));

describe('тексты секции «Проверьте свой сайт» и политики ПД', () => {
  it.each(APPROVED)('T1 %s в ru.json равен утвержденному дословно', (path, text) => {
    expect(valueAt(ru, path)).toBe(text);
  });

  it.each(AUDIT_PATHS)('T2 %s есть в en.json и не пуст', (path) => {
    const value = valueAt(en, path);

    expect(typeof value, `${path} в en.json`).toBe('string');
    expect((value as string).trim()).not.toBe('');
  });

  it('T3 редакция политики в ru.json сменилась', () => {
    const updated = valueAt(ru, 'privacy.updated');

    expect(typeof updated).toBe('string');
    expect(updated).not.toBe(PREVIOUS_PRIVACY_UPDATED);
  });

  it.each(EN_FORM_SECTIONS)('T4 en: раздел политики %s называет форму «Check your site»', (section) => {
    const strings = stringsOf(valueAt(en, `privacy.sections.${section}`));

    expect(strings.length, `строки раздела privacy.sections.${section}`).toBeGreaterThan(0);
    expect(
      strings.filter((text) => text.includes(EN_FORM_TITLE)).length,
      `строка с «${EN_FORM_TITLE}»`,
    ).toBeGreaterThan(0);
  });
});
