/**
 * Разметка без текстов подсказок: подсказка к слову словаря (`role="tooltip"`, закрытая — `hidden`) стоит в разметке
 * сразу после слова, а проверки текста страницы сравнивают текст, который читается подряд.
 */
export const withoutTooltips = (html: string) => html.replace(/<span[^>]*role="tooltip"[^>]*>[^<]*<\/span>/g, '');
