/**
 * Слова, которых нет в текстах услуги: способ работы не раскрываем, права на файлы — без «исключительного права»
 * и «уникальности». «ИИ» — слово целиком и с учетом регистра, остальное — без учета регистра.
 */
const FORBIDDEN: Record<Locale, RegExp[]> = {
  ru: [/(^|[^\p{L}])ИИ([^\p{L}]|$)/u, /нейросет/iu, /сгенерир/iu, /исключительн/iu, /уникальн/iu],
  en: [/\bAI\b/i, /neural/i, /generat/i, /exclusive/i, /unique/i],
};

const TRANSLATION_TODO = resolve(import.meta.dirname, '../../messages/TRANSLATION-TODO.md');

const WAITING_HEADING = '## Ждет вычитки Николая';

const valueAt = (root: unknown, path: string): unknown =>
  path.split('.').reduce<unknown>((node, key) => {
    if (node !== null && typeof node === 'object') {
      return (node as Record<string, unknown>)[key];
    }

    return undefined;
  }, root);

/** Все строки поддерева с полным путем: индекс массива — числом, как в `valueAt`. */
const entriesOf = (value: unknown, path: string): Entry[] => {
  if (typeof value === 'string') {
    return [{ path, text: value }];
  }

  if (value !== null && typeof value === 'object') {
    return Object.entries(value).flatMap(([key, child]) => entriesOf(child, `${path}.${key}`));
  }

  return [];
};

const logoEntries = (locale: Locale) => LOGO_ROOTS.flatMap((root) => entriesOf(valueAt(MESSAGES[locale], root), root));

/** Корни услуги, которых нет в переводе: без них проверки слов и формы прошли бы на пустом месте. */
const missingRoots = (locale: Locale) =>
  LOGO_ROOTS.filter((root) => {
    const value = valueAt(MESSAGES[locale], root);

    return value === null || typeof value !== 'object';
  });

/** Пути строк в формате файла вычитки: `{a,b}` раскрывается в варианты, `*` — любой хвост пути. */
const expandBraces = (pattern: string): string[] => {
  const open = pattern.indexOf('{');

  if (open === -1) {
    return [pattern];
  }

  let depth = 0;
  let close = open;

  for (let index = open; index < pattern.length; index += 1) {
    if (pattern[index] === '{') {
      depth += 1;
    } else if (pattern[index] === '}') {
      depth -= 1;

      if (depth === 0) {
        close = index;
        break;
      }
    }
  }

  const options: string[] = [];
  let start = open + 1;
  depth = 0;

  for (let index = open + 1; index < close; index += 1) {
    if (pattern[index] === '{') {
      depth += 1;
    } else if (pattern[index] === '}') {
      depth -= 1;
    } else if (pattern[index] === ',' && depth === 0) {
      options.push(pattern.slice(start, index));
      start = index + 1;
    }
  }

  options.push(pattern.slice(start, close));

  return options.flatMap((option) => expandBraces(`${pattern.slice(0, open)}${option}${pattern.slice(close + 1)}`));
};

const patternRegExp = (pattern: string) =>
  new RegExp(`^${pattern.replace(/[.+?^$()[\]\\|]/g, '\\$&').replace(/\*/g, '.+')}(\\..+)?$`);

/** Пути, названные в строках таблицы «Ждет вычитки»: все, что в обратных кавычках. */
const waitingPatterns = () => {
  const text = readFileSync(TRANSLATION_TODO, 'utf8');
  const start = text.indexOf(WAITING_HEADING);
  const rest = start === -1 ? '' : text.slice(start + WAITING_HEADING.length);
  const end = rest.search(/^## /m);
  const section = end === -1 ? rest : rest.slice(0, end);

  return section
    .split('\n')
    .filter((line) => line.trim().startsWith('|'))
    .flatMap((line) => [...line.matchAll(/`([^`]+)`/g)].map(([, pattern]) => pattern))
    .flatMap(expandBraces)
    .map(patternRegExp);
};

