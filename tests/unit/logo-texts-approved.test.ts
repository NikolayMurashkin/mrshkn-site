type Locale = 'ru' | 'en';

type Entry = { path: string; text: string };

const MESSAGES: Record<Locale, unknown> = { ru, en };

/** Ключи услуги в переводах: тариф, строка «Сверх тарифа», три уровня, тексты страницы. */
