describe('форма ключей услуги «Логотип и фирменный стиль» в ru и en одинаковая', () => {
  it('одинаковый набор ключей', () => {
    expect(missingRoots('ru'), 'ключи услуги в ru').toEqual([]);
    expect(missingRoots('en'), 'ключи услуги в en').toEqual([]);
    expect(logoEntries('en').map(({ path }) => path)).toEqual(logoEntries('ru').map(({ path }) => path));
  });

  it.each(LOGO_LISTS)('%s: одинаковое число строк в ru и en', (path) => {
    const ruList = valueAt(ru, path);
    const enList = valueAt(en, path);

    expect(Array.isArray(ruList), `${path} в ru — список`).toBe(true);
    expect(Array.isArray(enList), `${path} в en — список`).toBe(true);
    expect((enList as unknown[]).length).toBe((ruList as unknown[]).length);
  });

  it('все строки en непустые', () => {
    const empty = logoEntries('en')
      .filter(({ text }) => text.trim() === '')
      .map(({ path }) => path);

    expect(missingRoots('en'), 'ключи услуги в en').toEqual([]);
    expect(empty).toEqual([]);
  });
});

